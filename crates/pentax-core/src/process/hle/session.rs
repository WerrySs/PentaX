/// A generated export's owned guest site, derived only from the factory's
/// manifest and the retained provider bias. Never publicly constructible.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct AttestedSite {
    pub function: KnownFunction,
    pub module: usize,
    pub symbol: usize,
    pub stub_rva: u64,
    pub entry: u64,
    pub trap: u64,
    /// RIP and RCX after the interpreter's SYSCALL stop: the stub's RET.
    pub resume: u64,
}

/// A whole-session exact plan whose final module is the generated provider.
///
/// The owned [`SymbolicLinkPlan`] borrows the supplied and generated bytes.
/// Sites, provider position and service limits are private; there is no
/// constructor from an existing plan or site table.
pub struct HleSessionPlan<'a> {
    link: SymbolicLinkPlan<'a>,
    provider: usize,
    bias: u64,
    image: &'a [u8],
    sites: [AttestedSite; KnownFunction::ALL.len()],
    bindings: usize,
    services: MemoryServiceLimits,
}

impl fmt::Debug for HleSessionPlan<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("HleSessionPlan")
            .field("modules", &self.link.modules().len())
            .field("provider", &self.provider)
            .field("bias", &self.bias)
            .field("bindings", &self.bindings)
            .finish_non_exhaustive()
    }
}

impl<'a> HleSessionPlan<'a> {
    /// Read-only exact plan, including actual `Resolution` provenance.
    #[must_use]
    pub const fn link_plan(&self) -> &SymbolicLinkPlan<'a> {
        &self.link
    }
    #[must_use]
    pub const fn provider_index(&self) -> usize {
        self.provider
    }
    #[must_use]
    pub const fn provider_bias(&self) -> u64 {
        self.bias
    }
    /// Planned writes whose value is a generated provider definition.
    #[must_use]
    pub const fn provider_bindings(&self) -> usize {
        self.bindings
    }
    #[must_use]
    pub const fn service_limits(&self) -> MemoryServiceLimits {
        self.services
    }
    pub(super) const fn sites(&self) -> &[AttestedSite; KnownFunction::ALL.len()] {
        &self.sites
    }
}

/// Owned unstarted memory with attested generated provider sites.
///
/// Public access is read-only diagnostics. There is no mutable memory,
/// executor, native conversion or detached dispatch capability.
#[derive(Debug)]
pub struct PreparedHleSession {
    pub(super) session: UnstartedSession,
    pub(super) sites: [AttestedSite; KnownFunction::ALL.len()],
    services: MemoryServiceLimits,
    provider: usize,
    bias: u64,
    bindings: usize,
}

impl PreparedHleSession {
    #[must_use]
    pub fn memory(&self) -> &GuestMemory {
        self.session.memory()
    }
    #[must_use]
    pub fn primary_entry(&self) -> u64 {
        self.session.primary_entry()
    }
    #[must_use]
    pub fn module_count(&self) -> usize {
        self.session.module_count()
    }
    #[must_use]
    pub fn applied_relocations(&self) -> usize {
        self.session.applied_relocations()
    }
    #[must_use]
    pub const fn provider_index(&self) -> usize {
        self.provider
    }
    #[must_use]
    pub const fn provider_bias(&self) -> u64 {
        self.bias
    }
    #[must_use]
    pub const fn provider_bindings(&self) -> usize {
        self.bindings
    }
    #[must_use]
    pub const fn service_limits(&self) -> MemoryServiceLimits {
        self.services
    }
}

fn require(condition: bool, reason: &'static str) -> Result<(), HleError> {
    if condition {
        Ok(())
    } else {
        Err(HleError::InvalidProvider(reason))
    }
}

/// Plan supplied inputs plus this builder's own generated provider.
///
/// Input zero stays primary; the provider is appended after every supplied
/// input at a 16 KiB-aligned bias inside the 47-bit staging space. Ordinary
/// exact name/version/NID/type resolution applies, with no HLE priority,
/// NID-only fallback or discovery. A supplied same-type definition with the
/// same exact key is an `AmbiguousProvider` failure; a unique generated strong
/// definition wins over weak candidates. Under the typed resolver policy a
/// supplied candidate of a different symbol type is not a provider for that
/// import, so it neither competes with nor blocks the generated FUNC.
///
/// # Errors
/// Returns typed input, placement, budget, allocation, linking and provider
/// source-binding failures; no partial plan is returned.
pub fn plan_hle_session<'a>(
    inputs: &[ModuleInput<'a>],
    providers: &'a GeneratedProviders,
    placement: ProviderPlacement,
    limits: &HleLimits,
) -> Result<HleSessionPlan<'a>, HleError> {
    plan_session(inputs, providers, placement, limits, false)
}

/// Only the opt-in typed-TLS preparation can admit TLS-bearing inputs.
pub(super) fn plan_session<'a>(
    inputs: &[ModuleInput<'a>],
    providers: &'a GeneratedProviders,
    placement: ProviderPlacement,
    limits: &HleLimits,
    admit_tls: bool,
) -> Result<HleSessionPlan<'a>, HleError> {
    if inputs.is_empty() {
        return Err(HleError::NoPrimaryInput);
    }
    // A provider built under a larger allowance cannot bypass a tighter
    // session's generation-byte policy merely by being retained already.
    let provider_bytes = providers.image().len() as u64;
    if provider_bytes > limits.max_provider_bytes {
        return Err(HleError::LimitExceeded {
            kind: HleBudget::ProviderBytes,
            requested: provider_bytes,
            maximum: limits.max_provider_bytes,
        });
    }
    let bias = placement.load_bias;
    if !bias.is_multiple_of(PAGE_SIZE)
        || bias
            .checked_add(PROVIDER_SPAN)
            .is_none_or(|end| end > ADDRESS_LIMIT)
    {
        return Err(HleError::InvalidPlacement { load_bias: bias });
    }
    let provider = inputs.len();
    let count = provider as u64 + 1;
    if count > limits.linking.max_modules {
        return Err(HleError::LimitExceeded {
            kind: HleBudget::Modules,
            requested: count,
            maximum: limits.linking.max_modules,
        });
    }
    let mut session = Vec::new();
    session
        .try_reserve_exact(provider + 1)
        .map_err(|_| HleError::Allocation)?;
    session.extend_from_slice(inputs);
    let image = providers.image();
    let view = open_executable(image).map_err(HleError::Load)?;
    session.push(ModuleInput::new(view, bias));
    let link = plan_symbolic(&session, &limits.linking).map_err(HleError::Link)?;

    // Bind the planned provider module to the factory's exact bytes.
    let module = link
        .modules()
        .get(provider)
        .filter(|module| {
            link.modules().len() == provider + 1
                && module.id().index() == provider
                && module.load_bias() == bias
        })
        .ok_or(HleError::InvalidProvider("provider module position"))?;
    let runtime = module.runtime_plan();
    require(
        runtime.segments.len() == 2 && runtime.tls.is_none() && runtime.relro.is_empty(),
        "generated provider mapping",
    )?;
    let segment = &runtime.segments[0];
    require(
        std::ptr::eq(segment.file_bytes, &image[..CODE_SIZE])
            && segment.vaddr == 0
            && segment.mem_size == PAGE_SIZE
            && segment.flags.raw() == 5,
        "generated provider bytes",
    )?;
    let data = &runtime.segments[1];
    require(
        std::ptr::eq(data.file_bytes, &image[CODE_SIZE..])
            && data.file_bytes.len() as u64 == DATA_BYTES
            && data.vaddr == HEAP_TRACE_RVA
            && data.mem_size == PAGE_SIZE
            && data.flags.raw() == 6,
        "generated provider data storage",
    )?;
    if !admit_tls
        && let Some(module) = link
            .modules()
            .iter()
            .position(|module| module.runtime_plan().tls.is_some())
    {
        return Err(HleError::UnsupportedTls { module });
    }
    require(
        link.patches()
            .iter()
            .all(|patch| patch.consumer().index() != provider),
        "generated provider relocations",
    )?;

    let mut sites = [AttestedSite {
        function: KnownFunction::Memcpy,
        module: provider,
        symbol: 0,
        stub_rva: 0,
        entry: 0,
        trap: 0,
        resume: 0,
    }; KnownFunction::ALL.len()];
    for (site, entry) in sites.iter_mut().zip(providers.manifest()) {
        let address = bias
            .checked_add(entry.stub_rva)
            .filter(|address| {
                address
                    .checked_add(STUB_SIZE)
                    .is_some_and(|end| end <= bias + CODE_SIZE as u64)
            })
            .ok_or(HleError::InvalidProvider("generated stub placement"))?;
        *site = AttestedSite {
            function: entry.function,
            module: provider,
            symbol: entry.symbol,
            stub_rva: entry.stub_rva,
            entry: address,
            trap: address + TRAP_OFFSET,
            resume: address + RESUME_OFFSET,
        };
    }
    // Every resolved symbol must be a manifest function, one of its fixed
    // exact alias rows, or the separately typed fixed data object. Aliases
    // authorize no additional sites. R_X86_64_64 retains its S + A arithmetic.
    let mut bindings = 0;
    for patch in link.patches() {
        let Resolution::Definition(symbol) = patch.resolution() else {
            continue;
        };
        if symbol.module.index() != provider {
            continue;
        }
        let record = patch.source().record;
        let addend = if record.kind() == 1 { record.addend } else { 0 };
        require(
            ((NEED_FLAG_SYMBOL..NEED_FLAG_SYMBOL + NEED_FLAG_SYMBOLS).contains(&symbol.symbol)
                && record.kind() != 7
                && (bias + NEED_FLAG_RVA).wrapping_add_signed(addend) == patch.value())
                || sites.iter().any(|site| {
                    site.module == symbol.module.index()
                        && function_for_symbol(symbol.symbol) == Some(site.function)
                        && site.entry.wrapping_add_signed(addend) == patch.value()
                }),
            "provider binding outside the generated manifest",
        )?;
        bindings += 1;
    }
    Ok(HleSessionPlan {
        link,
        provider,
        bias,
        image,
        sites,
        bindings,
        services: limits.services,
    })
}

/// Stage the retained plan once and attest its generated provider in place.
///
/// Every deferred relocation is refused before staging; no TLS is prepared.
/// After `load_symbolic`, each staged stub must equal the factory's bytes at
/// its manifest position; code is R+X and immutable, trace data is R+W/NX.
///
/// # Errors
/// Returns `DeferredRelocations`, `Staging` or `InvalidProvider`; failures
/// drop the unpublished address space.
pub fn prepare_hle_session(
    plan: &HleSessionPlan<'_>,
    limits: &SessionLoadLimits,
) -> Result<PreparedHleSession, HleError> {
    if let Some(module) = plan
        .link
        .modules()
        .iter()
        .position(|module| module.runtime_plan().tls.is_some())
    {
        return Err(HleError::UnsupportedTls { module });
    }
    let deferred = plan.link.deferred_count();
    if deferred != 0 {
        return Err(HleError::DeferredRelocations { count: deferred });
    }
    let session = load_symbolic(&plan.link, limits).map_err(HleError::Staging)?;
    attest(&session.memory, plan)?;
    Ok(PreparedHleSession {
        session,
        sites: plan.sites,
        services: plan.services,
        provider: plan.provider,
        bias: plan.bias,
        bindings: plan.bindings,
    })
}

pub(super) fn attest(
    memory: &impl crate::memory::service::ServiceMemory,
    plan: &HleSessionPlan<'_>,
) -> Result<(), HleError> {
    for site in &plan.sites {
        let rva = site.stub_rva as usize;
        let expected = stub(site.function);
        require(
            plan.image.get(rva..rva + expected.len()) == Some(&expected[..]),
            "generated source stub",
        )?;
        let mut staged = [0; STUB_SIZE as usize];
        memory
            .fetch(site.entry, &mut staged)
            .map_err(|_| HleError::InvalidProvider("staged stub is not executable"))?;
        require(staged == expected, "staged stub bytes")?;
        let mut trap = [0; 2];
        memory
            .fetch(site.trap, &mut trap)
            .map_err(|_| HleError::InvalidProvider("staged trap is not executable"))?;
        require(
            trap == [0x0f, 0x05] && site.resume == site.trap + 2,
            "staged trap and resume site",
        )?;
    }
    for page in (plan.bias..plan.bias + PAGE_SIZE).step_by(PAGE_SIZE as usize) {
        require(
            memory.read(page, &mut [0]).is_ok()
                && memory.fetch(page, &mut [0]).is_ok()
                && matches!(
                    memory.preflight_write(page, 1),
                    Err(MemoryError::PermissionDenied(_))
                ),
            "provider page must be R+X and not writable",
        )?;
    }
    let data = plan.bias + HEAP_TRACE_RVA;
    require(
        memory.preflight_read(data, PAGE_SIZE).is_ok()
            && memory.preflight_write(data, PAGE_SIZE).is_ok()
            && matches!(
                memory.fetch(data, &mut [0]),
                Err(MemoryError::PermissionDenied(_))
            ),
        "provider trace page must be R+W and not executable",
    )?;
    Ok(())
}
