//! Owning exact-linker planning and source-bound staging of generated providers.

use super::catalog::KnownFunction;
use super::dispatch::MemoryServiceLimits;
use super::provider::{
    CODE_SIZE, DATA_BYTES, GeneratedProviders, HEAP_TRACE_RVA, NEED_FLAG_RVA, NEED_FLAG_SYMBOL,
    NEED_FLAG_SYMBOLS, PROVIDER_SPAN, RESUME_OFFSET, STUB_SIZE, TRAP_OFFSET, function_for_symbol,
    stub,
};
use super::{HleBudget, HleError, HleLimits, ProviderPlacement};
