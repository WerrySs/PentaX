fn stub_entry(function: KnownFunction) -> u64 {
    PROVIDER_BIAS + 0x100 + 0x10 * function.index() as u64
}

/// A supplied copy of the generated bytes with each export's info byte replaced.
fn supplied_copy(providers: &GeneratedProviders, info: u8) -> Vec<u8> {
    let mut bytes = providers.image().to_vec();
    for function in KnownFunction::ALL {
        bytes[SYMBOLS_AT + (function.index() + 1) * SYMBOL_SIZE + 4] = info;
    }
    bytes
}

#[test]
fn generated_provider_is_an_exact_original_protected_function_image() {
    let providers = providers();
    assert_eq!(providers.profile(), HleProfile::KytyObservedLibcInternalV1);
    assert_eq!(providers.function_count(), 17);
    let view = open_executable(providers.image()).unwrap();
    let runtime = view.runtime_plan().unwrap();
    assert_eq!(runtime.metadata.entry, 0);
    assert!(runtime.tls.is_none());
    assert_eq!(runtime.segments.len(), 2);
    let segment = &runtime.segments[0];
    assert_eq!(
        (segment.vaddr, segment.mem_size, segment.flags.raw()),
        (0, PAGE_SIZE, 5)
    );
    assert!(segment.file_bytes.len() as u64 <= PAGE_SIZE);

    let metadata = inspect_sce(&view, &Limits::DEFAULT, &SceLimits::DEFAULT)
        .unwrap()
        .into_metadata()
        .unwrap();
    let decoded = metadata.descriptors().decoded().unwrap();
    assert_eq!(decoded.module_info().len(), 2);
    assert_eq!(decoded.export_libraries().len(), 4);
    assert!(decoded.needed_modules().is_empty() && decoded.import_libraries().is_empty());
    let module = &decoded.module_info()[0];
    assert_eq!(module.name().as_bytes(), b"LibcInternal");
    assert_eq!((module.version_major(), module.version_minor()), (1, 1));
    assert_eq!(module.id().value(), 1);
    assert_eq!(module.encoding(), DescriptorEncoding::Classic);
    let library = &decoded.export_libraries()[0];
    assert_eq!(library.name().as_bytes(), b"LibcInternal");
    assert_eq!((library.version(), library.id().value()), (1, 1));

    let symbols = metadata.link().symbols();
    assert_eq!(symbols.len(), 67);
    assert!(symbols[0].name.as_ref().is_none_or(|name| name.is_empty()));
    assert_eq!(
        (symbols[0].info, symbols[0].value, symbols[0].size),
        (0, 0, 0)
    );
    for function in KnownFunction::ALL {
        let symbol = &symbols[function.index() + 1];
        let mut name = function.nid().to_vec();
        name.extend_from_slice(if function == KnownFunction::HeapGetTraceInfoSce {
            b"#D#C"
        } else if function == KnownFunction::HeapGetTraceInfo {
            b"#C#B"
        } else {
            b"#B#B"
        });
        assert_eq!(symbol.name.as_ref().unwrap().as_bytes(), name);
        assert_eq!(symbol.binding(), SymbolBinding::GLOBAL);
        assert_eq!(symbol.symbol_type(), SymbolType::FUNC);
        assert_eq!(symbol.visibility(), SymbolVisibility::PROTECTED);
        assert_eq!(
            (symbol.value, symbol.size),
            (stub_entry(function) - PROVIDER_BIAS, 8)
        );
        let at = symbol.value as usize;
        let bytes = &providers.image()[at..at + 8];
        assert_eq!(bytes, stub(function));
        // MOV EAX, imm32 (the PentaX protocol ID); SYSCALL; RET.
        assert_eq!(bytes[0], 0xb8);
        assert_eq!(
            u32::from_le_bytes(bytes[1..5].try_into().unwrap()),
            0x5058_4801 + function.index() as u32
        );
        assert_eq!(&bytes[5..], [0x0f, 0x05, 0xc3]);
    }
}

#[test]
fn provider_byte_budget_is_inclusive_and_checked_before_generation() {
    let size = providers().image().len() as u64;
    let mut limits = HleLimits {
        max_provider_bytes: size - 1,
        ..HleLimits::default()
    };
    assert_eq!(
        build_hle_providers(HleProfile::KytyObservedLibcInternalV1, &limits).unwrap_err(),
        HleError::LimitExceeded {
            kind: HleBudget::ProviderBytes,
            requested: size,
            maximum: size - 1,
        }
    );
    limits.max_provider_bytes = size;
    build_hle_providers(HleProfile::KytyObservedLibcInternalV1, &limits).unwrap();
}

#[test]
fn exact_typed_binding_resolves_generated_functions_in_both_domains_and_encodings() {
    let providers = providers();
    for dynlib in [false, true] {
        for encoding in [
            DescriptorEncoding::Classic,
            DescriptorEncoding::Variant1Observed,
        ] {
            let mut consumer = minimal_consumer();
            consumer.dynlib = dynlib;
            consumer.encoding = encoding;
            let consumer = consumer.build().unwrap();
            let plan = plan_one(&consumer, &providers).unwrap();
            assert_eq!(plan.provider_index(), 1);
            assert_eq!(plan.provider_bias(), PROVIDER_BIAS);
            assert_eq!(plan.provider_bindings(), 4);
            assert_eq!(plan.link_plan().deferred_count(), 0);
            for (slot, patch) in plan.link_plan().patches().iter().enumerate() {
                let function = KnownFunction::ALL[slot];
                assert_eq!(patch.address(), CONSUMER_BIAS + 0x4000 + 8 * slot as u64);
                assert_eq!(patch.value(), stub_entry(function));
                assert!(matches!(
                    patch.resolution(),
                    Resolution::Definition(symbol)
                        if symbol.module.index() == 1 && symbol.symbol == slot + 1
                ));
            }
            for (site, function) in plan.sites().iter().zip(KnownFunction::ALL) {
                assert_eq!(site.function, function);
                assert_eq!(site.entry, stub_entry(function));
                assert_eq!(site.resume, stub_entry(function) + 7);
            }
            let prepared = prepare_hle_session(&plan, &SessionLoadLimits::default()).unwrap();
            assert_eq!(prepared.module_count(), 2);
            assert_eq!(prepared.applied_relocations(), 4);
            assert_eq!(prepared.provider_bindings(), 4);
        }
    }
}

#[test]
fn wrong_names_versions_types_and_nids_keep_typed_linker_failures() {
    let providers = providers();
    let one = |import: Import| {
        let mut consumer = minimal_consumer();
        consumer.imports = vec![import];
        consumer
    };
    let memcpy = Import::function(KnownFunction::Memcpy);
    let mut cases = Vec::new();
    let names: [(&'static [u8], &'static [u8]); 3] = [
        (b"libc", b"LibcInternal"),
        (b"LibcInternal", b"libScelibcInternal"),
        (b"libcinternal", b"LibcInternal"),
    ];
    for (module, library) in names {
        let mut consumer = one(memcpy);
        consumer.module_name = module;
        consumer.library_name = library;
        cases.push((consumer, "missing"));
    }
    let mut absent = one(memcpy);
    absent.imports[0].nid = *b"AAAAAAAAAAA";
    cases.push((absent, "missing"));
    for (major, minor, version) in [(1, 0, 1), (2, 1, 1), (1, 1, 2)] {
        let mut consumer = one(memcpy);
        (consumer.major, consumer.minor, consumer.version) = (major, minor, version);
        cases.push((consumer, "version"));
    }
    cases.push((
        one(Import {
            symbol_type: 1,
            relocation: 6,
            ..memcpy
        }),
        "type",
    ));
    for (consumer, expected) in cases {
        let bytes = consumer.build().unwrap();
        let error = plan_one(&bytes, &providers).unwrap_err();
        let HleError::Link(error) = error else {
            panic!("expected a linker failure, got {error:?}");
        };
        match expected {
            "missing" => assert!(matches!(error, SymbolicError::MissingProvider { .. })),
            "version" => assert!(matches!(
                error,
                SymbolicError::VersionMismatch {
                    available: DescriptorVersions {
                        module_major: 1,
                        module_minor: 1,
                        library: 1,
                    },
                    ..
                }
            )),
            _ => assert!(matches!(
                error,
                SymbolicError::UnsupportedSymbol {
                    reason: UnsupportedSymbol::TypeMismatch,
                    symbol,
                } if symbol.module.index() == 1 && symbol.symbol == 1
            )),
        }
    }
}

#[test]
fn supplied_strong_competitors_are_ambiguous_and_generated_strong_wins_over_weak() {
    let providers = providers();
    let consumer = minimal_consumer().build().unwrap();
    let copy = providers.image().to_vec();
    let error = plan_with(
        &[(&consumer[..], CONSUMER_BIAS), (&copy[..], SUPPLIED_BIAS)],
        &providers,
    )
    .unwrap_err();
    assert!(matches!(
        error,
        HleError::Link(SymbolicError::AmbiguousProvider { first, second, .. })
            if first.module.index() == 1 && second.module.index() == 2
    ));
    let weak = supplied_copy(&providers, 0x22);
    let plan = plan_with(
        &[(&consumer[..], CONSUMER_BIAS), (&weak[..], SUPPLIED_BIAS)],
        &providers,
    )
    .unwrap();
    assert_eq!(plan.provider_bindings(), 4);
    assert!(plan.link_plan().patches().iter().all(|patch|
        matches!(patch.resolution(), Resolution::Definition(symbol) if symbol.module.index() == 2)
    ));
}

#[test]
fn supplied_wrong_type_candidates_follow_the_existing_typed_resolver_policy() {
    // A supplied OBJECT with the same exact key is not a FUNC provider for
    // these imports, so it neither competes with nor blocks the generated
    // definitions. This is existing linker policy, not an HLE priority.
    let providers = providers();
    let consumer = minimal_consumer().build().unwrap();
    let object = supplied_copy(&providers, 0x11);
    let plan = plan_with(
        &[(&consumer[..], CONSUMER_BIAS), (&object[..], SUPPLIED_BIAS)],
        &providers,
    )
    .unwrap();
    assert_eq!(plan.provider_index(), 2);
    assert_eq!(plan.provider_bindings(), 4);
    for patch in plan.link_plan().patches() {
        assert!(matches!(
            patch.resolution(),
            Resolution::Definition(symbol) if symbol.module.index() == 2
        ));
    }
}

#[test]
fn placement_primary_and_module_budget_fail_before_linking() {
    let providers = providers();
    let consumer = minimal_consumer().build().unwrap();
    let inputs = [ModuleInput::new(
        open_executable(&consumer).unwrap(),
        CONSUMER_BIAS,
    )];
    let limits = HleLimits::default();
    assert_eq!(
        plan_hle_session(&[], &providers, placement(), &limits).unwrap_err(),
        HleError::NoPrimaryInput
    );
    for load_bias in [
        PROVIDER_BIAS + 0x1000,
        ADDRESS_LIMIT,
        ADDRESS_LIMIT - PAGE_SIZE / 2,
        u64::MAX - PAGE_SIZE + 1,
    ] {
        assert_eq!(
            plan_hle_session(
                &inputs,
                &providers,
                ProviderPlacement { load_bias },
                &limits
            )
            .unwrap_err(),
            HleError::InvalidPlacement { load_bias }
        );
    }
    let highest = ProviderPlacement {
        load_bias: ADDRESS_LIMIT - 2 * PAGE_SIZE,
    };
    assert_eq!(
        plan_hle_session(&inputs, &providers, highest, &limits)
            .unwrap()
            .provider_bindings(),
        4
    );
    let overlapping = ProviderPlacement {
        load_bias: CONSUMER_BIAS,
    };
    assert!(matches!(
        plan_hle_session(&inputs, &providers, overlapping, &limits).unwrap_err(),
        HleError::Link(SymbolicError::OverlappingModulePages { .. })
    ));
    let mut limits = HleLimits::default();
    limits.linking.max_modules = 1;
    assert_eq!(
        plan_hle_session(&inputs, &providers, placement(), &limits).unwrap_err(),
        HleError::LimitExceeded {
            kind: HleBudget::Modules,
            requested: 2,
            maximum: 1,
        }
    );
    limits.linking.max_modules = 2;
    limits.linking.max_lookup_steps = 0;
    assert!(matches!(
        plan_hle_session(&inputs, &providers, placement(), &limits).unwrap_err(),
        HleError::Link(SymbolicError::LimitExceeded {
            budget: SymbolicBudget::LookupSteps,
            ..
        })
    ));
}

#[test]
fn preparation_refuses_any_deferred_relocation_and_tls_without_staging() {
    let providers = providers();
    let mut consumer = minimal_consumer();
    // R_X86_64_PC32 is outside the supported relocation policy.
    consumer.imports[0].relocation = 2;
    let bytes = consumer.build().unwrap();
    let plan = plan_one(&bytes, &providers).unwrap();
    assert_eq!(plan.link_plan().deferred_count(), 1);
    assert_eq!(
        prepare_hle_session(&plan, &SessionLoadLimits::default()).unwrap_err(),
        HleError::DeferredRelocations { count: 1 }
    );

    // Replace the RELRO header with an initialized PT_TLS template.
    let mut bytes = minimal_consumer().build().unwrap();
    program(&mut bytes, 3, 7, 4, [0xd00, 0xd00, 8, 16, 8]);
    assert_eq!(
        plan_one(&bytes, &providers).unwrap_err(),
        HleError::UnsupportedTls { module: 0 }
    );
}

#[test]
fn prepared_provider_is_attested_rx_and_exposes_only_read_only_diagnostics() {
    let providers = providers();
    let original = providers.image().to_vec();
    let consumer = minimal_consumer().build().unwrap();
    let plan = plan_one(&consumer, &providers).unwrap();
    let prepared = prepare_hle_session(&plan, &SessionLoadLimits::default()).unwrap();
    assert_eq!(prepared.primary_entry(), CONSUMER_BIAS + CODE as u64);
    assert_eq!(prepared.provider_index(), 1);
    assert_eq!(prepared.provider_bias(), PROVIDER_BIAS);
    assert_eq!(prepared.service_limits(), HleLimits::default().services);
    let memory = prepared.memory();
    for function in KnownFunction::ALL {
        let mut staged = [0; 8];
        memory.fetch(stub_entry(function), &mut staged).unwrap();
        assert_eq!(staged, stub(function));
        if KnownFunction::MEMORY.contains(&function) {
            let mut slot = [0; 8];
            memory
                .read(
                    CONSUMER_BIAS + 0x4000 + 8 * function.index() as u64,
                    &mut slot,
                )
                .unwrap();
            assert_eq!(u64::from_le_bytes(slot), stub_entry(function));
        }
    }
    assert!(matches!(
        memory.preflight_write(PROVIDER_BIAS, 1),
        Err(MemoryError::PermissionDenied(_))
    ));
    // Generated bytes are unchanged and reproducible.
    assert_eq!(providers.image(), original);
    assert_eq!(super::providers().image(), original);
}

#[test]
fn attestation_rejects_changed_stub_bytes_and_writable_provider_pages() {
    let providers = providers();
    let consumer = minimal_consumer().build().unwrap();
    let plan = plan_one(&consumer, &providers).unwrap();
    let limits = SessionLoadLimits::default();
    let mut session = load_symbolic(plan.link_plan(), &limits).unwrap();
    attest(&session.memory, &plan).unwrap();
    let memory = &mut session.memory;
    memory
        .protect(PROVIDER_BIAS, PAGE_SIZE, Permissions::READ_WRITE)
        .unwrap();
    let id_byte = stub_entry(KnownFunction::Memset) + 1;
    memory.write(id_byte, &[0x55]).unwrap();
    memory
        .protect(PROVIDER_BIAS, PAGE_SIZE, Permissions::READ_EXECUTE)
        .unwrap();
    assert_eq!(
        attest(memory, &plan).unwrap_err(),
        HleError::InvalidProvider("staged stub bytes")
    );
    let original = stub(KnownFunction::Memset)[1];
    memory
        .protect(PROVIDER_BIAS, PAGE_SIZE, Permissions::READ_WRITE)
        .unwrap();
    memory.write(id_byte, &[original]).unwrap();
    memory
        .protect(PROVIDER_BIAS, PAGE_SIZE, Permissions::new(true, true, true))
        .unwrap();
    assert_eq!(
        attest(memory, &plan).unwrap_err(),
        HleError::InvalidProvider("provider page must be R+X and not writable")
    );
}
